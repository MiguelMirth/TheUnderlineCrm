// Generates src/api/schema.ts (types only) from the FastAPI app's OpenAPI document.
// Run after any API or model change: npm --prefix web run gen:api
//
// Python comes from ENGINE_PYTHON if set, else the repo .venv.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const root = path.resolve(webDir, "..");

function pythonExe() {
  if (process.env.ENGINE_PYTHON) return process.env.ENGINE_PYTHON;
  const win = path.join(root, ".venv", "Scripts", "python.exe");
  const nix = path.join(root, ".venv", "bin", "python");
  if (existsSync(win)) return win;
  if (existsSync(nix)) return nix;
  throw new Error("No .venv python found. Run `uv sync` in the repo root or set ENGINE_PYTHON.");
}

const dump = [
  "import json, sys",
  "sys.path.insert(0, 'src')",
  "from engine.api import create_app",
  "sys.stdout.write(json.dumps(create_app(load_env=False, start_worker=False).openapi()))",
].join("\n");

const raw = execFileSync(pythonExe(), ["-c", dump], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const schema = JSON.parse(raw);

const ast = await openapiTS(schema);
const body = astToString(ast);
const header = "// Generated by web/scripts/gen-api.mjs from FastAPI /openapi.json. Do not edit by hand.\n";
const out = path.join(webDir, "src", "api", "schema.ts");
writeFileSync(out, header + body);
console.log(`wrote ${path.relative(root, out)} (${readFileSync(out, "utf8").length} bytes)`);
